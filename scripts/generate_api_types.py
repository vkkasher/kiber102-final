"""Generate the checked-in public schema and TypeScript types from FastAPI.

Run from any directory; --check verifies that committed artifacts match the API.
No database connections, credentials or external requests are needed.
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def type_name(value):
    return re.sub(r'\W', '_', value)


def schema_type(schema):
    if '$ref' in schema:
        return type_name(schema['$ref'].rsplit('/', 1)[-1])
    if 'const' in schema:
        return json.dumps(schema['const'], ensure_ascii=False)
    if 'enum' in schema:
        return ' | '.join(json.dumps(value, ensure_ascii=False) for value in schema['enum']) or 'never'
    for keyword, joiner in [('anyOf', ' | '), ('oneOf', ' | '), ('allOf', ' & ')]:
        if keyword in schema:
            return joiner.join(schema_type(item) for item in schema[keyword])
    kind = schema.get('type')
    if isinstance(kind, list):
        return ' | '.join(schema_type({**schema, 'type': item}) for item in kind)
    if kind in {'integer', 'number'}:
        return 'number'
    if kind in {'string', 'boolean', 'null'}:
        return kind
    if kind == 'array':
        return 'Array<' + schema_type(schema.get('items', {})) + '>'
    if kind == 'object' or 'properties' in schema:
        properties = schema.get('properties', {})
        required = set(schema.get('required', []))
        fields = [f'{json.dumps(name, ensure_ascii=False)}{"" if name in required else "?"}: {schema_type(value)};'
                  for name, value in sorted(properties.items())]
        additional = schema.get('additionalProperties', not bool(properties))
        if additional:
            fields.append('[key: string]: ' + (schema_type(additional) if isinstance(additional, dict) else 'unknown') + ';')
        return '{ ' + ' '.join(fields) + ' }' if fields else 'Record<string, never>'
    return 'unknown'


def render_types(schemas):
    digest = hashlib.sha256(json.dumps(schemas, sort_keys=True).encode()).hexdigest()
    header = '// Generated by scripts/generate_api_types.py from FastAPI OpenAPI. Do not edit.\n'
    header += f'// Schema SHA256: {digest}\n\n'
    return header + '\n\n'.join(f'export type {type_name(name)} = {schema_type(schema)};'
                                for name, schema in sorted(schemas.items())) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    sys.path.insert(0, str(ROOT))
    from apps.api.app.main import create_app
    app = create_app('sqlite://')
    schema = app.openapi()
    app.state.engine.dispose()
    outputs = {
        ROOT / 'docs' / 'openapi.json': json.dumps(schema, ensure_ascii=False, indent=2, sort_keys=True) + '\n',
        ROOT / 'apps' / 'web' / 'src' / 'lib' / 'generated-api.d.ts': render_types(schema['components']['schemas']),
    }
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')
    if stale:
        print('Regenerate API contracts: python scripts/generate_api_types.py')
        for name in stale:
            print(name)
        return 1
    print('API contracts are current.' if args.check else 'Generated OpenAPI and TypeScript contracts.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
